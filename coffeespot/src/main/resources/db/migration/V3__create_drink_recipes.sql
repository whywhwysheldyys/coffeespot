CREATE TABLE drink_recipes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    drink_id BIGINT NOT NULL,
    ingredient_id BIGINT NOT NULL,
    quantity_needed NUMERIC(10, 2) NOT NULL,
    CONSTRAINT fk_recipe_drink FOREIGN KEY (drink_id) REFERENCES coffee_drinks(id) ON DELETE CASCADE,
    CONSTRAINT fk_recipe_ingredient FOREIGN KEY (ingredient_id) REFERENCES ingredients(id),
    CONSTRAINT uq_drink_ingredient UNIQUE (drink_id, ingredient_id)
);